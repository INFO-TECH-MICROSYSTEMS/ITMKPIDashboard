export const DEFAULT_LANGUAGE = 'en';

export function getLanguageDirection(code: string): 'ltr' | 'rtl' {
  const lang = SUPPORTED_LANGUAGES.find((l) => l.code === code);
  return lang ? lang.dir : 'ltr';
}

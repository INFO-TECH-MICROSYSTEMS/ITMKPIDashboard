const langFiles = fs.readdirSync(localesDir).filter(f => f.endsWith('.json'));

for (const file of langFiles) {
  const lang = file.replace('.json', '');
  const filePath = path.join(localesDir, file);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf-8'));

  // Merge specific translation or fallback to enKPI
  const kpiData = mapLangToKPI[lang] || enKPI;
  data.kpiPlatform = {
    ...enKPI,
    ...kpiData,
    categories: {
      ...enKPI.categories,
      ...(kpiData.categories || {})
    },
    executiveView: {
      ...enKPI.executiveView,
      ...(kpiData.executiveView || {})
    }
  };

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf-8');
  console.log(`Updated ${file} with kpiPlatform translations`);
}

